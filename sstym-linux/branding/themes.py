def kitty_conf(k, name):
    lines = [f"# {name} — kitty colours", f"background_opacity {k['opacity']}",
             f"foreground {k['fg']}", f"background {k['bg']}", f"selection_background {k['sel']}",
             f"cursor {k['cursor']}"]
    lines += [f"color{i} {c}" for i, c in enumerate(k["colors"])]
    return "\n".join(lines) + "\n"


for key, p in PAL.items():
    d = os.path.join(SHARE, "themes", key)
    os.makedirs(d, exist_ok=True)
    q = dict(p)
    q["border_css"] = p["border"].replace("rgba", "rgba")
    open(os.path.join(d, "waybar.css"), "w").write(WAYBAR.format(**q))
    open(os.path.join(d, "dock.css"), "w").write(DOCK.format(**q))
    open(os.path.join(d, "swaync.css"), "w").write(SWAYNC.format(**q))
    open(os.path.join(d, "rofi.rasi"), "w").write(ROFI.format(**q))
    open(os.path.join(d, "kitty.conf"), "w").write(kitty_conf(p["kitty"], p["name"]))
    open(os.path.join(d, "theme.env"), "w").write(
        f'NAME="{p["name"]}"\nWALLPAPER=/usr/share/sstym/wallpapers/{p["wallpaper"]}\nWIDGETS={p["widgets"]}\n')
    # border colours for hyprland.lua (one value per line: first = inactive)
    open(os.path.join(d, "borders"), "w").write("\n".join([p["border_inactive"]] + p["border_active"]) + "\n")

